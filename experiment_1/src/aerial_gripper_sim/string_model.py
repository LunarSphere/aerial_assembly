"""Physical colliding string backends and string telemetry."""

from __future__ import annotations

import abc
import logging
import math
from dataclasses import dataclass
from typing import Any

import mujoco
import numpy as np

from .config import StringConfig

LOGGER = logging.getLogger(__name__)


@dataclass
class StringTelemetry:
    name: str
    segment_tension_n: list[float]
    mean_tension_n: float
    peak_tension_n: float
    endpoint_tension_n: tuple[float, float]
    current_length_m: float
    rest_length_m: float
    slack_m: float
    contact_count: int
    contact_impulse_ns: float
    minimum_payload_distance_m: float
    endpoint_error_m: float = 0.0
    axial_strain: float = 0.0
    captured: bool = False


class StringModel(abc.ABC):
    """Backend-neutral colliding cable interface."""

    def __init__(self, config: StringConfig, anchors: list[dict[str, Any]]):
        self.config = config
        self.anchors = anchors

    def extension_xml(self) -> str:
        return ""

    def equality_fragments(self) -> list[str]:
        return []

    @abc.abstractmethod
    def xml_fragments(self, count: int | None = None) -> list[str]:
        """Return MJCF fragments to place inside the gripper body."""

    @abc.abstractmethod
    def initialize_pretension(self, model: mujoco.MjModel) -> dict[str, float]:
        """Shorten physical rest lengths and report requested rest geometry."""

    @abc.abstractmethod
    def sample(
        self,
        model: mujoco.MjModel,
        data: mujoco.MjData,
        payload_geom_ids: set[int],
    ) -> list[StringTelemetry]:
        """Sample physical cable state."""


@dataclass
class _CableRuntime:
    name: str
    geom_names: list[str]
    first_site_name: str
    last_site_name: str
    equality_name: str
    nominal_length_m: float
    geom_ids: list[int] | None = None
    first_site_id: int = -1
    last_site_id: int = -1
    equality_id: int = -1


class InextensibleCableModel(StringModel):
    """Exactly inextensible capsule chains generated by MuJoCo composite cable."""

    def __init__(self, config: StringConfig, anchors: list[dict[str, Any]]):
        super().__init__(config, anchors)
        self.cables: list[_CableRuntime] = []

    def extension_xml(self) -> str:
        if not self.cables:
            return ""
        return (
            '<extension><plugin plugin="mujoco.elasticity.cable"/></extension>'
        )

    def xml_fragments(self, count: int | None = None) -> list[str]:
        selected = self.anchors[: count if count is not None else len(self.anchors)]
        self.cables = []
        fragments: list[str] = []
        for anchor in selected:
            index = int(anchor["index"])
            left = np.asarray(anchor["left_m"], dtype=float)
            right = np.asarray(anchor["right_m"], dtype=float)
            points = _sagging_polyline(
                left,
                right,
                self.config.segments_per_string,
                self.config.slack_length_m,
            )
            nominal_length = float(np.sum(np.linalg.norm(np.diff(points, axis=0), axis=1)))
            prefix = f"cable{index}_"
            vertex_text = " ".join(f"{value:.12g}" for value in points.reshape(-1))
            density = (
                self.config.density_kg_per_m3
                * self.config.numerical_mass_scale
            )
            geom_names = [
                f"{prefix}G{segment}"
                for segment in range(self.config.segments_per_string)
            ]
            runtime = _CableRuntime(
                name=f"string_{index}",
                geom_names=geom_names,
                first_site_name=f"{prefix}S_first",
                last_site_name=f"{prefix}S_last",
                equality_name=f"{prefix}right_attachment",
                nominal_length_m=nominal_length,
            )
            self.cables.append(runtime)
            fragments.append(
                f"""
                <composite prefix="{prefix}" type="cable" initial="ball"
                  vertex="{vertex_text}">
                  <plugin plugin="mujoco.elasticity.cable">
                    <config key="twist" value="0"/>
                    <config key="bend" value="0"/>
                    <config key="vmax" value="0"/>
                  </plugin>
                  <joint kind="main" damping="0.00002" armature="0.000001"/>
                  <geom type="capsule" size="{self.config.radius_m:.12g}"
                    density="{density:.12g}"
                    contype="4" conaffinity="26" condim="3"
                    friction="{' '.join(map(str, self.config.friction))}"
                    solref="0.003 1" solimp="0.9 0.95 0.001 0.5 2"
                    margin="0.00002" gap="0"
                    rgba="0.95 0.25 0.08 1"/>
                </composite>
                """
            )
        return fragments

    def equality_fragments(self) -> list[str]:
        return [
            (
                f'<connect name="{cable.equality_name}" '
                f'site1="{cable.last_site_name}" '
                f'site2="anchor_right_{cable.name.removeprefix("string_")}" '
                'solref="0.0005 1" '
                'solimp="0.999 0.9999 0.00001 0.5 2"/>'
            )
            for cable in self.cables
        ]

    def initialize_pretension(self, model: mujoco.MjModel) -> dict[str, float]:
        for cable in self.cables:
            cable.geom_ids = [
                mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, name)
                for name in cable.geom_names
            ]
            cable.first_site_id = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_SITE, cable.first_site_name
            )
            cable.last_site_id = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_SITE, cable.last_site_name
            )
            cable.equality_id = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_EQUALITY, cable.equality_name
            )
            if (
                any(value < 0 for value in cable.geom_ids)
                or cable.first_site_id < 0
                or cable.last_site_id < 0
                or cable.equality_id < 0
            ):
                raise ValueError(f"Could not resolve generated MuJoCo cable {cable.name}")
        return {
            cable.name: cable.nominal_length_m
            for cable in self.cables
        }

    def sample(
        self,
        model: mujoco.MjModel,
        data: mujoco.MjData,
        payload_geom_ids: set[int],
    ) -> list[StringTelemetry]:
        result: list[StringTelemetry] = []
        for cable in self.cables:
            assert cable.geom_ids is not None
            vertices = _cable_vertices(model, data, cable)
            current_length = float(
                np.sum(np.linalg.norm(np.diff(vertices, axis=0), axis=1))
            )
            endpoint_error = float(
                np.linalg.norm(
                    data.site_xpos[cable.last_site_id]
                    - data.site_xpos[
                        mujoco.mj_name2id(
                            model,
                            mujoco.mjtObj.mjOBJ_SITE,
                            f"anchor_right_{cable.name.removeprefix('string_')}",
                        )
                    ]
                )
            )
            tension = _equality_force(data, cable.equality_id)
            contact_count, impulse = _geom_payload_contacts(
                model, data, set(cable.geom_ids), payload_geom_ids
            )
            result.append(
                StringTelemetry(
                    name=cable.name,
                    segment_tension_n=[tension] * len(cable.geom_ids),
                    mean_tension_n=tension,
                    peak_tension_n=tension,
                    endpoint_tension_n=(tension, tension),
                    current_length_m=current_length,
                    rest_length_m=cable.nominal_length_m,
                    slack_m=float(
                        max(
                            0.0,
                            cable.nominal_length_m
                            - np.linalg.norm(vertices[-1] - vertices[0]),
                        )
                    ),
                    contact_count=contact_count,
                    contact_impulse_ns=impulse,
                    minimum_payload_distance_m=_minimum_hook_distance(
                        model, data, vertices, payload_geom_ids
                    ),
                    endpoint_error_m=endpoint_error,
                    axial_strain=(
                        (current_length - cable.nominal_length_m)
                        / cable.nominal_length_m
                    ),
                    captured=_is_captured(
                        model, data, vertices, payload_geom_ids, self.config.radius_m
                    ),
                )
            )
        return result


class FlexStringModel(StringModel):
    """MuJoCo 1-D flex cables with colliding capsule elements."""

    def __init__(self, config: StringConfig, anchors: list[dict[str, Any]]):
        super().__init__(config, anchors)
        self.names: list[str] = []

    def xml_fragments(self, count: int | None = None) -> list[str]:
        selected = self.anchors[: count if count is not None else len(self.anchors)]
        fragments: list[str] = []
        self.names = []
        segments = self.config.segments_per_string
        area = math.pi * self.config.radius_m**2
        for anchor in selected:
            left = np.asarray(anchor["left_m"], dtype=float)
            right = np.asarray(anchor["right_m"], dtype=float)
            span = float(np.linalg.norm(right - left))
            center = (left + right) / 2.0
            name = f"string_{int(anchor['index'])}"
            self.names.append(name)
            spacing = span / segments
            # Flex contact at sub-millimetre radius is ill-conditioned when each
            # numerical node has sub-microgram mass. The scale is explicit and
            # recorded; reported material density remains the physical value.
            mass = (
                self.config.density_kg_per_m3
                * area
                * span
                * self.config.numerical_mass_scale
            )
            # The supplied pairs differ negligibly in y/z, so a grid along local
            # X exactly connects their fitted inner-mouth centers.
            fragments.append(
                f"""
                <flexcomp name="{name}" type="grid" dim="1"
                  count="{segments + 1} 1 1"
                  spacing="{spacing:.12g} {spacing:.12g} {spacing:.12g}"
                  pos="{center[0]:.12g} {center[1]:.12g} {center[2]:.12g}"
                  radius="{self.config.radius_m:.12g}"
                  mass="{mass:.12g}" inertiabox="{self.config.radius_m * 2:.12g}"
                  rgba="0.95 0.25 0.08 1">
                  <edge equality="true" solref="0.003 1"
                    solimp="0.9 0.95 0.001 0.5 2"
                    stiffness="0" damping="{self.config.damping_n_s_per_m:.12g}"/>
                  <contact contype="4" conaffinity="26" condim="3"
                    friction="{' '.join(map(str, self.config.friction))}"
                    solref="0.012 1" solimp="0.7 0.9 0.002 0.5 2"
                    margin="0.00002" gap="0" selfcollide="none"/>
                  <pin id="0 {segments}"/>
                </flexcomp>
                """
            )
        return fragments

    def initialize_pretension(self, model: mujoco.MjModel) -> dict[str, float]:
        achieved: dict[str, float] = {}
        extension_per_edge = (
            self.config.pretension_n / self.config.axial_stiffness_n_per_m
        )
        for name in self.names:
            flex_id = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_FLEX, name
            )
            if flex_id < 0:
                continue
            start = int(model.flex_edgeadr[flex_id])
            number = int(model.flex_edgenum[flex_id])
            current_rest = model.flexedge_length0[start : start + number]
            if np.any(current_rest <= extension_per_edge):
                raise ValueError(
                    f"Pretension {self.config.pretension_n} N would require "
                    f"non-positive rest edges in {name}"
                )
            current_rest[:] -= extension_per_edge
            achieved[name] = float(np.sum(current_rest))
        return achieved

    def sample(
        self,
        model: mujoco.MjModel,
        data: mujoco.MjData,
        payload_geom_ids: set[int],
    ) -> list[StringTelemetry]:
        result: list[StringTelemetry] = []
        for name in self.names:
            flex_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_FLEX, name)
            start = int(model.flex_edgeadr[flex_id])
            number = int(model.flex_edgenum[flex_id])
            edge_slice = slice(start, start + number)
            lengths = np.asarray(data.flexedge_length[edge_slice])
            rest = np.asarray(model.flexedge_length0[edge_slice])
            velocities = np.asarray(data.flexedge_velocity[edge_slice])
            tension = np.maximum(
                0.0,
                self.config.axial_stiffness_n_per_m * (lengths - rest)
                + self.config.damping_n_s_per_m * velocities,
            )
            contact_count, impulse = _flex_payload_contacts(
                model, data, flex_id, payload_geom_ids
            )
            vertex_start = int(model.flex_vertadr[flex_id])
            vertex_count = int(model.flex_vertnum[flex_id])
            vertices = np.asarray(
                data.flexvert_xpos[vertex_start : vertex_start + vertex_count]
            )
            result.append(
                StringTelemetry(
                    name=name,
                    segment_tension_n=tension.tolist(),
                    mean_tension_n=float(np.mean(tension)),
                    peak_tension_n=float(np.max(tension)),
                    endpoint_tension_n=(float(tension[0]), float(tension[-1])),
                    current_length_m=float(np.sum(lengths)),
                    rest_length_m=float(np.sum(rest)),
                    slack_m=float(max(0.0, np.sum(rest) - np.linalg.norm(vertices[-1] - vertices[0]))),
                    contact_count=contact_count,
                    contact_impulse_ns=impulse,
                    minimum_payload_distance_m=_minimum_hook_distance(
                        model, data, vertices, payload_geom_ids
                    ),
                )
            )
        return result


def make_string_model(
    config: StringConfig, anchors: list[dict[str, Any]]
) -> StringModel:
    if config.backend == "flex":
        return FlexStringModel(config, anchors)
    if config.backend == "segmented":
        LOGGER.warning(
            "strings.backend=segmented is deprecated; using the exact-length "
            "MuJoCo composite cable backend"
        )
    return InextensibleCableModel(config, anchors)


def _sagging_polyline(
    left: np.ndarray,
    right: np.ndarray,
    segments: int,
    extra_length_m: float,
) -> np.ndarray:
    """Return a sine-sag polyline with an exact requested total length."""
    parameter = np.linspace(0.0, 1.0, segments + 1)
    baseline = left[None, :] + parameter[:, None] * (right - left)[None, :]
    target = float(np.linalg.norm(right - left) + extra_length_m)
    if extra_length_m <= 0:
        return baseline

    def with_amplitude(amplitude: float) -> np.ndarray:
        points = baseline.copy()
        points[:, 2] -= amplitude * np.sin(np.pi * parameter)
        return points

    lower = 0.0
    upper = max(0.001, math.sqrt(extra_length_m * target))
    while True:
        candidate = with_amplitude(upper)
        length = float(np.sum(np.linalg.norm(np.diff(candidate, axis=0), axis=1)))
        if length >= target:
            break
        upper *= 2.0
    for _ in range(60):
        middle = (lower + upper) / 2.0
        candidate = with_amplitude(middle)
        length = float(np.sum(np.linalg.norm(np.diff(candidate, axis=0), axis=1)))
        if length < target:
            lower = middle
        else:
            upper = middle
    return with_amplitude((lower + upper) / 2.0)


def _cable_vertices(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    cable: _CableRuntime,
) -> np.ndarray:
    """Recover the ordered capsule centerline, starting at S_first."""
    current = np.asarray(data.site_xpos[cable.first_site_id]).copy()
    vertices = [current]
    assert cable.geom_ids is not None
    for geom_id in cable.geom_ids:
        center = np.asarray(data.geom_xpos[geom_id])
        axis = np.asarray(data.geom_xmat[geom_id]).reshape(3, 3)[:, 2]
        half_length = float(model.geom_size[geom_id, 1])
        candidates = (center - axis * half_length, center + axis * half_length)
        next_point = max(candidates, key=lambda point: np.linalg.norm(point - current))
        vertices.append(np.asarray(next_point).copy())
        current = next_point
    return np.asarray(vertices)


def _equality_force(data: mujoco.MjData, equality_id: int) -> float:
    rows = np.flatnonzero(
        (np.asarray(data.efc_type) == int(mujoco.mjtConstraint.mjCNSTR_EQUALITY))
        & (np.asarray(data.efc_id) == equality_id)
    )
    if not len(rows):
        return 0.0
    return float(np.linalg.norm(np.asarray(data.efc_force)[rows]))


def _geom_payload_contacts(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    cable_geom_ids: set[int],
    payload_geom_ids: set[int],
) -> tuple[int, float]:
    count = 0
    impulse = 0.0
    force = np.zeros(6)
    for index in range(data.ncon):
        contact = data.contact[index]
        pair = {int(contact.geom[0]), int(contact.geom[1])}
        if pair.intersection(cable_geom_ids) and pair.intersection(payload_geom_ids):
            count += 1
            mujoco.mj_contactForce(model, data, index, force)
            impulse += float(np.linalg.norm(force[:3]) * model.opt.timestep)
    return count, impulse


def _is_captured(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    vertices_world: np.ndarray,
    payload_geom_ids: set[int],
    radius_m: float,
) -> bool:
    """Classify a cable centerline as occupying a measured hook undercut."""
    if not payload_geom_ids:
        return False
    uses_j_hooks = any(
        "_collision_j_return_" in (
            mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, geom_id) or ""
        )
        for geom_id in payload_geom_ids
    )
    geom_id = next(iter(payload_geom_ids))
    body_id = int(model.geom_bodyid[geom_id])
    rotation = np.asarray(data.xmat[body_id]).reshape(3, 3)
    local = (vertices_world - data.xpos[body_id]) @ rotation
    if uses_j_hooks:
        return _is_captured_by_j_hook(local, radius_m)

    wall_y = (-0.0053635, -0.0009635, 0.0034365, 0.0078365)
    within_x = np.abs(local[:, 0]) <= 0.0174
    below_lip = local[:, 2] <= 0.0454019 - radius_m
    above_valley = local[:, 2] >= 0.0406 + radius_m
    for y in wall_y:
        # The hook cavity is bounded by the vertical retaining wall on +Y and
        # the measured sloping tooth face on -Y. A cable below the lip and
        # wholly between those boundaries is positioned for upward capture;
        # merely touching the outside of the lip nose does not qualify.
        normalized_height = np.clip(
            (local[:, 2] - 0.0406) / (0.0480 - 0.0406), 0.0, 1.0
        )
        left_face_y = y - (
            0.00084 + normalized_height * (0.0034365 - 0.00084)
        )
        within_cavity = (
            (local[:, 1] >= left_face_y + radius_m)
            & (local[:, 1] <= y - radius_m)
        )
        if np.any(within_x & below_lip & above_valley & within_cavity):
            return True
    return False


def _is_captured_by_j_hook(local: np.ndarray, radius_m: float) -> bool:
    """Test occupancy below a J return using its measured section boundaries."""
    within_x = np.abs(local[:, 0]) <= 0.0174
    above_valley = local[:, 2] >= 0.0400 + radius_m
    # A centerline is mechanically below the rounded nose only when the yarn's
    # upper surface is below its lowest point.
    below_return = local[:, 2] <= 0.045488 - radius_m
    slope_bottom = np.array([-0.00616697, 0.04033811])
    slope_top = np.array([-0.0088, 0.0480])
    stem_bottom = np.array([-0.00519603, 0.04041361])
    stem_top = np.array([-0.00474569, 0.04675879])
    pitch = 0.0044
    z = local[:, 2]
    slope_fraction = np.clip(
        (z - slope_bottom[1]) / (slope_top[1] - slope_bottom[1]), 0.0, 1.0
    )
    stem_fraction = np.clip(
        (z - stem_bottom[1]) / (stem_top[1] - stem_bottom[1]), 0.0, 1.0
    )
    for index in range(4):
        left_face_y = (
            slope_bottom[0]
            + slope_fraction * (slope_top[0] - slope_bottom[0])
            + index * pitch
        )
        right_face_y = (
            stem_bottom[0]
            + stem_fraction * (stem_top[0] - stem_bottom[0])
            + index * pitch
        )
        within_cavity = (
            (local[:, 1] >= left_face_y + radius_m)
            & (local[:, 1] <= right_face_y - radius_m)
        )
        if np.any(within_x & above_valley & below_return & within_cavity):
            return True
    return False


def _flex_payload_contacts(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    flex_id: int,
    payload_geom_ids: set[int],
) -> tuple[int, float]:
    count = 0
    impulse = 0.0
    force = np.zeros(6)
    for index in range(data.ncon):
        contact = data.contact[index]
        flex_values = {
            int(value)
            for value in np.asarray(contact.flex).reshape(-1)
            if int(value) >= 0
        }
        geom_values = {
            int(value)
            for value in np.asarray(contact.geom).reshape(-1)
            if int(value) >= 0
        }
        if flex_id in flex_values and geom_values.intersection(payload_geom_ids):
            count += 1
            mujoco.mj_contactForce(model, data, index, force)
            impulse += float(np.linalg.norm(force[:3]) * model.opt.timestep)
    return count, impulse


def _minimum_hook_distance(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    vertices_world: np.ndarray,
    payload_geom_ids: set[int],
) -> float:
    """Distance to the four measured hook-valley centerlines."""
    if not payload_geom_ids:
        return 1.0
    geom_id = next(iter(payload_geom_ids))
    body_id = int(model.geom_bodyid[geom_id])
    rotation = np.asarray(data.xmat[body_id]).reshape(3, 3)
    local = (vertices_world - data.xpos[body_id]) @ rotation
    within_span = np.abs(local[:, 0]) <= 0.0175
    candidates = local[within_span]
    if not len(candidates):
        candidates = local
    centers_y = np.asarray((-0.0055, -0.0010, 0.0035, 0.0080))
    dy = candidates[:, None, 1] - centers_y[None, :]
    dz = candidates[:, None, 2] - 0.041
    return float(np.min(np.sqrt(dy**2 + dz**2)))
